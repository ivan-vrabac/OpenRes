#!/usr/bin/env python3
"""Writes the OpenRes 0.3 economy (server/gamedata.py) as Markdown tables, for reviewing the numbers.

    python tools/economy_report.py > ECONOMY.md
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "server"))
import gamedata as g  # noqa: E402


def fmt(x: float) -> str:
    for unit, div in (("T", 1e12), ("B", 1e9), ("M", 1e6), ("k", 1e3)):
        if abs(x) >= div:
            return f"{x / div:.3g}{unit}"
    return f"{x:.3g}" if x < 10 else f"{x:.0f}"


def unlock_level(item: str) -> int:
    for op, (_, _, items, _) in g.OPERATIONS.items():
        if item in items and items[item][1] is not None:
            return g.TIER_UNLOCK[items[item][0]]
    return 0


def main() -> None:
    p = print
    p("# OpenRes 0.3 economy (generated)\n")
    p("Generated by `tools/economy_report.py` from `server/gamedata.py`. Credits are system prices.\n")

    p("## Hexes (raw items)\n")
    p("| Operation | Land | Item | Tier | Unlock Campus | Units/h at 100 % | Price | Income/h | Build | Lease (90 d) |")
    p("|---|---|---|---|---|---|---|---|---|---|")
    for op, (name, land, items, _) in g.OPERATIONS.items():
        for item, (tier, rate) in items.items():
            if item == g.ENERGY:
                kwh = g.SOLAR_KWH_PER_HOUR if op == "solar_farm" else g.WIND_KWH_PER_HOUR
                p(f"| {name} | {g.LANDS[land]} | Electricity | {tier} | {g.TIER_UNLOCK[tier]} | {kwh:.0f} kWh | "
                  f"{g.PRICES[g.ENERGY]:.2f}/kWh | {fmt(kwh * g.PRICES[g.ENERGY])} | {fmt(g.TIER_INCOME[tier] * g.HEX_BUILD_HOURS)} | "
                  f"{fmt(g.TIER_INCOME[tier] * g.LEASE_HOURS)} |")
                continue
            p(f"| {name} | {g.LANDS[land]} | {g.ITEM_NAMES[item]} | {tier} | {g.TIER_UNLOCK[tier]} | {rate} | "
              f"{fmt(g.PRICES[item])} | {fmt(g.hex_income(item))} | {fmt(g.hex_build_cost(item))} | {fmt(g.lease_cost(item))} |")
    p("\nSea fishing (Fishing port) comes after the first release (needs the coastline map).\n")

    p("## Factories (inside the Campus)\n")
    p("Each level runs the batch below once more in parallel. Profit = value added per hour per level.\n")
    p("| Factory | Unlock Campus | Recipe (per level, per batch) | Hours | kWh | Profit/h/level | Build | Level 10 -> 11 |")
    p("|---|---|---|---|---|---|---|---|")
    for f, (name, unlock, _m, recipes) in g.FACTORIES.items():
        s = g.factory_scale(f)
        for i, (inputs, (out, qty), hours, kwh) in enumerate(recipes):
            ins = " + ".join(f"{q * s:,} {g.ITEM_NAMES[x].lower()}" for x, q in inputs.items())
            outq = f"{qty * s:,} kWh" if out == g.ENERGY else (f"{qty * s:,} mg" if out == "ta180m" else f"{qty * s:,}")
            p(f"| {name if i == 0 else ''} | {unlock if i == 0 else ''} | {ins} -> {outq} {g.ITEM_NAMES[out].lower()} | "
              f"{hours} | {kwh * s:,} | {fmt(g.recipe_profit_per_hour(f, i))} | "
              f"{fmt(g.factory_upgrade_cost(f, 0)) if i == 0 else ''} | {fmt(g.factory_upgrade_cost(f, 10)) if i == 0 else ''} |")

    p("\n## Product prices\n")
    p("| Item | Price |")
    p("|---|---|")
    raw = g.raw_items()
    for item, name in g.ITEM_NAMES.items():
        if item not in raw and item != g.ENERGY:
            unit = " per mg (no market: for XP only)" if item == "ta180m" else ""
            p(f"| {name} | {fmt(g.PRICES[item])}{unit} |")
    p(f"| Electricity | {g.PRICES[g.ENERGY]:.2f} per kWh |")

    p("\n## Campus\n")
    p("| Level | Stage | Supervisors | Queue slots | Survey radius | Unlocks | To next level: credits | materials | storage level |")
    p("|---|---|---|---|---|---|---|---|---|")
    for lv in range(1, g.CAMPUS_MAX + 1):
        b = g.campus_stage(lv)
        unlocks = [g.FACTORIES[f][0] for f in g.FACTORIES if g.FACTORIES[f][1] == lv]
        unlocks += [f"tier-{t} hexes" for t, u in g.TIER_UNLOCK.items() if u == lv and lv > 1]
        if lv < g.CAMPUS_MAX:
            up = g.campus_upgrade(lv)
            mats = ", ".join(f"{fmt(q)} {g.ITEM_NAMES[i].lower()}" for i, q in up["materials"].items())
            nxt = f"{fmt(up['credits'])} | {mats} | {up['storage']}"
        else:
            nxt = "max | | "
        p(f"| {lv} | {b} | {lv * g.SUPERVISORS_PER_LEVEL} | {g.queue_slots(lv)} | "
          f"{g.survey_max_radius(lv):,} m | {', '.join(unlocks)} | {nxt} |")

    p("\n## Supervisor education (one at a time, plus the queue)\n")
    p("| Step | Name | Boost | Time | Books | Credits |")
    p("|---|---|---|---|---|---|")
    for step, (name, boost, hours, books, credits) in g.EDUCATION.items():
        p(f"| {step} | {name} | +{boost:.0%} | {hours} h | {books:,} | {fmt(credits)} |")
    total_h = sum(e[2] for e in g.EDUCATION.values())
    p(f"\nOne supervisor to Master's: {total_h} h. All {g.CAMPUS_MAX * g.SUPERVISORS_PER_LEVEL}: "
      f"{total_h * g.CAMPUS_MAX * g.SUPERVISORS_PER_LEVEL:,} h = {total_h * g.CAMPUS_MAX * g.SUPERVISORS_PER_LEVEL / 24 / 365:.1f} years.\n")

    p("## Government survey\n")
    p("| Radius | Tax | Per 100 m-area | Wait | Campus level needed |")
    p("|---|---|---|---|---|")
    for r in (100, 300, 1_000, 2_000, 5_000):
        area = (r / 100) ** 2
        need = min(lv for lv, rr in g.SURVEY_RADIUS_BY_CAMPUS if rr >= r)
        p(f"| {r:,} m | {fmt(g.survey_tax(r))} | {fmt(g.survey_tax(r) / area)} | {g.survey_wait_minutes(r):.0f} min | {need} |")

    p("\n## Central Storage\n")
    p("| Level | Capacity | Upgrade cost |")
    p("|---|---|---|")
    for lv in (1, 5, 10, 15, 20, 25):
        p(f"| {lv} | {fmt(g.storage_capacity(lv))} | {fmt(g.storage_upgrade_cost(lv))} |")

    p("\n## Dark matter research\n")
    p("| Level | Ta-180m needed | Bonus (total) |")
    p("|---|---|---|")
    for lv in (1, 2, 5, 10, 20):
        p(f"| {lv} | {g.dark_matter_cost_mg(lv) / 1000:.2f} g | +{lv * g.DARK_MATTER_BONUS:.0%} |")

    p("\n## Login streak\n")
    p(", ".join(f"day {d}+: {fmt(c)}/day" for d, c in g.STREAK_REWARD))


if __name__ == "__main__":
    main()
